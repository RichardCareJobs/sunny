-- 20261118_reject_apify_non_pub_ie_gb.sql
--
-- Why: the 25 Aug 2026 Apify import seeded every scraped Dublin/London record into
-- venue_details as 'unknown_after_enrichment'. SearchCore.isListedVenueRow lists any
-- row that isn't rejected_*, so hotels, bus stops, theatres and landmarks showed up as
-- Sunny venues in search. This sets the venue_enrichment.classification = 'non_pub'
-- rows to 'rejected_not_eligible' (the status the Newcastle NSW import uses).
--
-- Scope (agreed 18 Nov 2026):
--   * non_pub only. 'review' rows (263) are left as-is for editorial review.
--   * venue_enrichment.raw->>'countryCode' in ('IE','GB'). The 5 non_pub rows with no
--     countryCode are out of scope and only listed in step 1d.
--   * enrichment_source = 'apify_google_maps' and qualification_status =
--     'unknown_after_enrichment', so rows later qualified by the Places API
--     (enrichment_source = 'places_api') are never touched.
--   * Exactly the 173 place_ids in 20261118_reject_apify_non_pub_ie_gb.ids.txt
--     (md5 of the comma-joined, C-sorted list: d1aeb04ae0ca0642968ca3bd72e2c84d).
--
-- Prerequisite: commit 67ef343 ("Never refresh or overwrite rejected_ venues from
-- Places") must be live, otherwise a card open re-asks Places after 30 days and can
-- overwrite the rejection. Separate from the Newcastle import.
--
-- Run each step on its own in the Supabase SQL editor (or via MCP), in order.

-- ── 1. Dry run (read-only) ───────────────────────────────────────────────────

